// Runs the firmware's own first-boot configuration (OpenCat.ino with MAIN_SKETCH commented out) on the host
// and dumps the resulting on-board and I2C EEPROM images, so the fuzz harness boots from a factory-fresh robot.
#define AUTO_INIT
#define BITTLE
#define NyBoard_V1_2
#define OTHER_MODULES
#include "src/OpenCat.h"

#include <stdio.h>

#include "mock.h"

// The generator is linked non-PIE, so the AVR's flat address space maps onto real pointers losslessly.
uint8_t mock_pgm_read_byte(uintptr_t a) { return *(const uint8_t *)a; }

// Skill::saveSkillInfoFromProgmemToOnboardEeprom() verbatim except for the skill count: upstream computes it as
// sizeof(skillNameWithType) / 2, which assumes the AVR's 2-byte pointers and is 4x too large on a 64-bit host.
static void save_skill_info() {
  int skillAddressShift = 0;
  unsigned int i2cEepromAddress = INITIAL_SKILL_DATA_ADDRESS;
  unsigned int theLastEEaddress = 0;
  const int nSkills = sizeof(skillNameWithType) / sizeof(skillNameWithType[0]);
  EEPROM.update(NUM_SKILLS, nSkills);
  for (byte s = 0; s < eeprom(NUM_SKILLS); s++) {
    theLastEEaddress = i2cEepromAddress;
    byte len = strlen(skillNameWithType[s]);
    EEPROM.update(SKILLS + skillAddressShift++, len - 1);
    for (byte l = 0; l < len; l++) EEPROM.update(SKILLS + skillAddressShift++, skillNameWithType[s][l]);
    int8_t period = pgm_read_byte(progmemPointer[s]);
    EEPROM.update(SKILLS + skillAddressShift++, period);
    if (!EEPROMOverflow)
      if (skillNameWithType[s][len - 1] == 'I') {
        EEPROMWriteInt(SKILLS + skillAddressShift, i2cEepromAddress);
        skill.copyDataFromPgmToI2cEeprom(i2cEepromAddress, (unsigned int)(uintptr_t)progmemPointer[s]);
      }
    skillAddressShift += 2;
  }
  EEPROMWriteInt(SERIAL_BUFF, theLastEEaddress);
}

static void dump(FILE *f, const char *name, const uint8_t *d, size_t n) {
  fprintf(f, "static const uint8_t %s[%zu] = {", name, n);
  for (size_t i = 0; i < n; i++) fprintf(f, "%s%u,", i % 24 ? "" : "\n", d[i]);
  fprintf(f, "\n};\n");
}

int main(int argc, char **argv) {
  if (argc != 2) return 2;
  mock::reset_peripherals();
  memset(mock::eeprom(), 0xFF, mock::kEepromSize);
  memset(mock::i2c_eeprom(), 0xFF, mock::kI2cEepromSize);
  writeConst();  // the rest of configureEEPROM()
  save_skill_info();
  servoSetup();
  FILE *f = fopen(argv[1], "w");
  if (!f) return 1;
  fprintf(f, "// Generated by gen_eeprom.cpp from the firmware's own configureEEPROM(); do not edit.\n");
  dump(f, "kFactoryEeprom", mock::eeprom(), mock::kEepromSize);
  dump(f, "kFactoryI2cEeprom", mock::i2c_eeprom(), mock::kI2cEepromSize);
  fclose(f);
  return 0;
}
